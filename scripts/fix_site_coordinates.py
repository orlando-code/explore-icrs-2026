def _read_js_export(path: Path, export_name: str) -> dict:
    source = path.read_text(encoding="utf-8")
    prefix = f"export const {export_name} = "
    start = source.index(prefix) + len(prefix)
    end = source.rindex(";\n")
    return json.loads(source[start:end])


def _write_js_export(path: Path, export_name: str, payload: dict, generator: str) -> None:
    body = (
        f"/** Generated by {generator} – do not edit by hand. */\n"
        f"export const {export_name} = {json.dumps(payload, ensure_ascii=False, indent=2)};\n"
    )
    path.write_text(body, encoding="utf-8")


_COORDS_CACHE_LOOKUP: dict[str, tuple[float, float]] | None = None


def _coords_lookup_from_rows(geocoded) -> dict[str, tuple[float, float]]:
    lookup: dict[str, tuple[float, float]] = {}
    for _, row in geocoded.iterrows():
        affiliation = str(row.get("affiliation") or "").strip()
        if not affiliation:
            continue
        try:
            lat = float(row.get("latitude"))
            lon = float(row.get("longitude"))
        except (TypeError, ValueError):
            continue
        if math.isnan(lat) or math.isnan(lon):
            continue
        lookup[affiliation] = (lat, lon)
        lookup[canonical_affiliation_key(affiliation).casefold()] = (lat, lon)
    return lookup


def _coords_by_affiliations(affiliations: list[str]) -> dict[str, tuple[float, float]]:
    unique = sorted({aff.strip() for aff in affiliations if aff and aff.strip()})
    if not unique:
        return {}
    try:
        geocoded = geocode_affiliations(unique, cache_only=True, show_progress=False)
    except (json.JSONDecodeError, OSError):
        return {}
    return _coords_lookup_from_rows(geocoded)


def _coords_from_cache(affiliation: str) -> tuple[float, float] | None:
    global _COORDS_CACHE_LOOKUP
    if _COORDS_CACHE_LOOKUP is None:
        _COORDS_CACHE_LOOKUP = {}
    key = affiliation.strip()
    if not key:
        return None
    cached = _COORDS_CACHE_LOOKUP.get(key) or _COORDS_CACHE_LOOKUP.get(
        canonical_affiliation_key(key).casefold()
    )
    if cached is not None:
        return cached
    lookup = _coords_by_affiliations([key])
    _COORDS_CACHE_LOOKUP.update(lookup)
    return lookup.get(key) or lookup.get(canonical_affiliation_key(key).casefold())


def delegate_affiliation_replacements() -> dict[str, str]:
    """Map corrupted delegate PDF affiliations to cleaned display names."""
    from src.delegates import delegate_affiliation_for_row, normalize_delegate_records

    import pandas as pd

    if not DELEGATES_PATH.exists():
        return {}

    payload = _load_json(DELEGATES_PATH)
    replacements: dict[str, str] = {}
    for raw_row in payload.get("delegates", []):
        normalized = normalize_delegate_records(pd.DataFrame([raw_row])).iloc[0]
        new_affiliation = delegate_affiliation_for_row(normalized)
        new_display = affiliation_base_name(new_affiliation) or str(
            normalized.get("organisation") or ""
        ).strip()
        if not new_display:
            continue

        old_candidates = {
            str(raw_row.get("affiliation") or "").strip(),
            str(raw_row.get("organisation") or "").strip(),
            re.sub(r"\s+", " ", str(raw_row.get("organisation") or "")).strip(),
            affiliation_base_name(str(raw_row.get("affiliation") or "")),
        }
        country = str(raw_row.get("country") or "").strip()
        if country:
            old_candidates.add(
                f"{str(raw_row.get('organisation') or '').strip()}, {country}"
            )
            old_candidates.add(
                re.sub(
                    r"\s+",
                    " ",
                    f"{str(raw_row.get('organisation') or '').strip()}, {country}",
                ).strip()
            )

        for old in old_candidates:
            if old and old not in {new_display, new_affiliation}:
                replacements[old] = new_display
    return replacements


def _sanitized_affiliation_display(affiliation: str) -> str | None:
    """Clean a stale exported affiliation string using delegate bleed rules."""
    from src.delegates import is_incomplete_organisation, sanitize_delegate_organisation

    cleaned = affiliation.strip()
    if not cleaned:
        return None

    base = affiliation_base_name(cleaned) or cleaned
    parts = [part.strip() for part in cleaned.split(",") if part.strip()]
    country = parts[-1] if len(parts) >= 2 else ""
    sanitized = sanitize_delegate_organisation(
        base,
        country=country,
    )
    if is_incomplete_organisation(sanitized):
        return None
    if sanitized and sanitized != cleaned and sanitized != base:
        return sanitized
    if sanitized and sanitized != cleaned:
        return sanitized
    return None


