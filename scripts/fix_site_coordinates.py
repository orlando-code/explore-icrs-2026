def _patch_emissions_pool_from_delegates(pool: dict, by_name: dict[str, str]) -> int:
    from src.delegates import is_incomplete_organisation, normalize_person_name

    changed = 0
    for attendee in pool.get("attendees", []):
        name = str(attendee.get("name") or "").strip()
        affiliation = str(attendee.get("affiliation") or "").strip()
        replacement = by_name.get(name.casefold()) or by_name.get(normalize_person_name(name))
        if not replacement or affiliation == replacement:
            continue
        attendee["affiliation"] = replacement
        changed += 1

    location_affiliations: dict[str, str] = {}
    for attendee in pool.get("attendees", []):
        location_id = attendee.get("location_id")
        affiliation = str(attendee.get("affiliation") or "").strip()
        if location_id and affiliation and not is_incomplete_organisation(affiliation):
            location_affiliations[str(location_id)] = affiliation

    for location in pool.get("locations", []):
        affiliation = str(location.get("affiliation") or "").strip()
        replacement = location_affiliations.get(str(location.get("id")))
        if not replacement and is_incomplete_organisation(affiliation):
            attendees = [
                str(item.get("affiliation") or "").strip()
                for item in pool.get("attendees", [])
                if item.get("location_id") == location.get("id")
            ]
            valid = [item for item in attendees if item and not is_incomplete_organisation(item)]
            if valid:
                replacement = max(set(valid), key=valid.count)
        if replacement and replacement != affiliation:
            location["affiliation"] = replacement
            changed += 1
    return changed


def _rebuild_emissions_locations(pool: dict, overrides: dict) -> int:
    attendees = pool.get("attendees", [])
    old_locations = {
        str(location.get("id")): location for location in pool.get("locations", [])
    }
    if not attendees:
        return 0

    groups: dict[str, dict] = {}
    affiliation_labels: list[str] = []
    for attendee in attendees:
        affiliation = str(attendee.get("affiliation") or "").strip()
        if not affiliation:
            continue
        affiliation_labels.append(affiliation)
        key = canonical_affiliation_key(affiliation).casefold()
        display = affiliation_display_name(affiliation) or affiliation
        bucket = groups.setdefault(
            key,
            {
                "affiliation": display,
                "attendees": [],
                "co2e_kg": 0.0,
            },
        )
        if len(display) > len(bucket["affiliation"]):
            bucket["affiliation"] = display
        bucket["attendees"].append(attendee)
        bucket["co2e_kg"] += float(attendee.get("co2e_kg") or 0)

    global _COORDS_CACHE_LOOKUP
    _COORDS_CACHE_LOOKUP = _coords_by_affiliations(affiliation_labels)

    locations: list[dict] = []
    for index, bucket in enumerate(
        sorted(groups.values(), key=lambda item: item["affiliation"].casefold()),
        start=1,
    ):
        loc_id = f"emis-loc-{index:04d}"
        count = len(bucket["attendees"])
        co2e_kg = round(bucket["co2e_kg"], 1)
        location = {
            "id": loc_id,
            "affiliation": bucket["affiliation"],
            "lat": None,
            "lon": None,
            "speaker_count": count,
            "travel_attendees": count,
            "co2e_kg": co2e_kg,
            "co2e_low_kg": co2e_kg,
            "co2e_high_kg": co2e_kg,
            "co2e_per_speaker_kg": round(co2e_kg / max(count, 1), 1),
            "distance_km": None,
        }
        if not _patch_location(location, overrides, allow_cache=True):
            for attendee in bucket["attendees"]:
                old = old_locations.get(str(attendee.get("location_id")))
                if not old or old.get("lat") is None or old.get("lon") is None:
                    continue
                if is_crf_cache_poison(
                    bucket["affiliation"],
                    {
                        "latitude": old["lat"],
                        "longitude": old["lon"],
                        "query_used": old.get("query_used"),
                    },
                ):
                    continue
                location["lat"] = old["lat"]
                location["lon"] = old["lon"]
                if old.get("geocode_level"):
                    location["geocode_level"] = old["geocode_level"]
                if old.get("distance_km") is not None:
                    location["distance_km"] = old["distance_km"]
                break
        for attendee in bucket["attendees"]:
            attendee["location_id"] = loc_id
        locations.append(location)

    changed = len(locations) != len(old_locations)
    pool["locations"] = locations
    pool["rankings"] = sorted(
        locations,
        key=lambda row: float(row.get("co2e_kg") or 0),
        reverse=True,
    )[:30]
    return changed or 1


def _affiliation_by_person_name() -> dict[str, str]:
    from src.delegates import (
        delegate_affiliation_for_row,
        is_incomplete_organisation,
        load_delegates,
        normalize_person_name,
    )
    from src.programme import load_talks

    mapping: dict[str, str] = {}

    def add_name(name: str, display: str) -> None:
        display = display.strip()
        if not name.strip() or not display or is_incomplete_organisation(display):
            return
        for key in {
            name.strip().casefold(),
            normalize_person_name(name),
        }:
            if key:
                mapping.setdefault(key, display)

    for _, row in load_delegates().iterrows():
        display = (
            affiliation_base_name(delegate_affiliation_for_row(row))
            or str(row.get("organisation") or "").strip()
        )
        add_name(str(row.get("full_name") or ""), display)

    talks = load_talks()
    for presenter, affiliation in (
        talks[["presenter", "affiliation"]].dropna().drop_duplicates().itertuples(index=False)
    ):
        display = affiliation_base_name(str(affiliation)) or str(affiliation).strip()
        add_name(str(presenter), display)

    return mapping


def _lookup_person_affiliation(by_name: dict[str, str], name: str) -> str | None:
    from src.delegates import normalize_person_name

    cleaned = str(name or "").strip()
    if not cleaned:
        return None
    return by_name.get(cleaned.casefold()) or by_name.get(normalize_person_name(cleaned))


def _infer_affiliation_for_node(node: dict, by_name: dict[str, str]) -> str | None:
    names: list[str] = []
    for key in ("name", "presenter", "label"):
        value = node.get(key)
        if isinstance(value, str) and value.strip():
            names.append(value.strip())
    for speaker in node.get("speakers", []) or []:
        if isinstance(speaker, str):
            names.append(speaker)
    for detail in node.get("speaker_details", []) or []:
        if isinstance(detail, dict) and detail.get("name"):
            names.append(str(detail["name"]))

    counts: dict[str, int] = {}
    for name in names:
        affiliation = _lookup_person_affiliation(by_name, name)
        if affiliation:
            counts[affiliation] = counts.get(affiliation, 0) + 1
    if not counts:
        return None
    return max(counts.items(), key=lambda item: item[1])[0]


def _patch_incomplete_affiliation_tree(node, by_name: dict[str, str]) -> int:
    from src.delegates import is_incomplete_organisation

    changed = 0
    if isinstance(node, dict):
        affiliation = node.get("affiliation")
        if isinstance(affiliation, str) and is_incomplete_organisation(affiliation):
            replacement = _infer_affiliation_for_node(node, by_name)
            if replacement and replacement != affiliation:
                node["affiliation"] = replacement
                changed += 1
        for value in node.values():
            changed += _patch_incomplete_affiliation_tree(value, by_name)
    elif isinstance(node, list):
        for item in node:
            changed += _patch_incomplete_affiliation_tree(item, by_name)
    return changed


def _patch_incomplete_emissions_affiliations(payload: dict) -> int:
    from src.delegates import is_incomplete_organisation

    by_name = _affiliation_by_person_name()
    changed = 0
    for pool_name in ("speakers", "all_delegates"):
        pool = payload.get(pool_name)
        if not pool:
            continue
        location_affiliations: dict[str, str] = {}
        for attendee in pool.get("attendees", []):
            affiliation = str(attendee.get("affiliation") or "").strip()
            if not is_incomplete_organisation(affiliation):
                continue
            name = str(attendee.get("name") or "").strip().casefold()
            replacement = by_name.get(name)
            if not replacement:
                from src.delegates import normalize_person_name

                replacement = by_name.get(normalize_person_name(attendee.get("name") or ""))
            if not replacement or replacement == affiliation:
                continue
            attendee["affiliation"] = replacement
            location_id = attendee.get("location_id")
            if location_id:
                location_affiliations[str(location_id)] = replacement
            changed += 1
        for location in pool.get("locations", []):
            affiliation = str(location.get("affiliation") or "").strip()
            if not is_incomplete_organisation(affiliation):
                continue
            replacement = location_affiliations.get(str(location.get("id")))
            if not replacement:
                loc_id = location.get("id")
                attendee_affs = [
                    str(attendee.get("affiliation") or "").strip()
                    for attendee in pool.get("attendees", [])
                    if attendee.get("location_id") == loc_id
                    and not is_incomplete_organisation(attendee.get("affiliation"))
                ]
                if attendee_affs:
                    replacement = max(set(attendee_affs), key=attendee_affs.count)
            if replacement and replacement != affiliation:
                location["affiliation"] = replacement
                changed += 1
    changed += _patch_incomplete_affiliation_tree(payload, by_name)
    return changed


def _sync_emissions_rankings(payload: dict) -> int:
    changed = 0
    for pool_name in ("speakers", "all_delegates"):
        pool = payload.get(pool_name)
        if not pool:
            continue
        by_id = {
            str(location.get("id")): str(location.get("affiliation") or "")
            for location in pool.get("locations", [])
            if location.get("id")
        }
        for ranking in pool.get("rankings", []):
            loc_id = str(ranking.get("id") or "")
            replacement = by_id.get(loc_id)
            if replacement and ranking.get("affiliation") != replacement:
                ranking["affiliation"] = replacement
                changed += 1
    return changed


def _patch_affiliation_strings(node, replacements: dict[str, str]) -> int:
    changed = 0
    if isinstance(node, dict):
        affiliation = node.get("affiliation")
        if isinstance(affiliation, str):
            replacement = replacements.get(affiliation.strip())
            if not replacement:
                replacement = _sanitized_affiliation_display(affiliation)
            if replacement and replacement != affiliation:
                node["affiliation"] = replacement
                changed += 1
        for value in node.values():
            changed += _patch_affiliation_strings(value, replacements)
    elif isinstance(node, list):
        for item in node:
            changed += _patch_affiliation_strings(item, replacements)
    return changed


def _patch_location(
    location: dict,
    overrides: dict,
    *,
    allow_cache: bool = False,
) -> bool:
    affiliation = location.get("affiliation") or ""
    coords = None
    override = _lookup_override(affiliation, overrides)
    if override and override.get("latitude") is not None:
        coords = (float(override["latitude"]), float(override["longitude"]))
    elif allow_cache:
        coords = _coords_from_cache(affiliation)
    if coords is None:
        lat = location.get("lat")
        lon = location.get("lon")
        if lat is None or lon is None:
            return False
        rounded = (round(float(lat), 6), round(float(lon), 6))
        if rounded not in COUNTRY_CENTROIDS:
            return False
        return False
    lat, lon = coords
    changed = location.get("lat") != lat or location.get("lon") != lon
    location["lat"] = lat
    location["lon"] = lon
    location["geocode_level"] = "institute"
    return changed


def _patch_object_tree(node, overrides: dict) -> int:
    changed = 0
    if isinstance(node, dict):
        affiliation = node.get("affiliation")
        if affiliation and "lat" in node and "lon" in node:
            if _patch_location(node, overrides):
                changed += 1
        for value in node.values():
            changed += _patch_object_tree(value, overrides)
    elif isinstance(node, list):
        for item in node:
            changed += _patch_object_tree(item, overrides)
    return changed

def patch_emissions_file(path: Path, overrides: dict) -> int:
    payload = _read_js_export(path, "EMISSIONS_DATA")
    replacements = {
        **delegate_affiliation_replacements(),
        **load_affiliation_display_aliases(),
    }
    replacements = {
        key: affiliation_display_name(value) or value
        for key, value in replacements.items()
    }
    by_name = _delegate_affiliation_display_by_name()
    changed = 0
    changed += _patch_incomplete_emissions_affiliations(payload)
    for pool_name in ("speakers", "all_delegates"):
        pool = payload.get(pool_name)
        if not pool:
            continue
        changed += _patch_emissions_pool_from_delegates(pool, by_name)
        changed += _patch_affiliation_strings(pool, replacements)
        changed += _rebuild_emissions_locations(pool, overrides)
        for location in pool.get("locations", []):
            affiliation = str(location.get("affiliation") or "").strip()
            display = affiliation_display_name(affiliation)
            if display and display != affiliation:
                location["affiliation"] = display
                changed += 1
            if location.get("lat") is None or location.get("lon") is None:
                if _patch_location(location, overrides, allow_cache=True):
                    changed += 1
    changed += _sync_emissions_rankings(payload)
    if changed:
        _write_js_export(path, "EMISSIONS_DATA", payload, "fix_site_coordinates.py")
    return changed


def _merge_speaker_details(details: list[dict]) -> list[dict]:
    merged: dict[str, dict] = {}
    for detail in details:
        if not isinstance(detail, dict):
            continue
        name = str(detail.get("name") or "").strip()
        if not name:
            continue
        key = name.casefold()
        existing = merged.get(key)
        if not existing:
            merged[key] = dict(detail)
            continue
        titles = list(existing.get("talk_titles") or [])
        seen = {str(title) for title in titles}
        for title in detail.get("talk_titles") or []:
            text = str(title)
            if text and text not in seen:
                titles.append(text)
                seen.add(text)
        existing["talk_titles"] = titles
        if len(str(detail.get("search_text") or "")) > len(str(existing.get("search_text") or "")):
            existing["search_text"] = detail.get("search_text")
    return sorted(merged.values(), key=lambda item: str(item.get("name") or "").casefold())


def _merge_map_locations(payload: dict) -> int:
    locations = payload.get("locations") or []
    if not locations:
        return 0

    grouped: dict[str, list[dict]] = {}
    for location in locations:
        affiliation = str(location.get("affiliation") or "").strip()
        display = affiliation_display_name(affiliation) or affiliation
        if display != affiliation:
            location["affiliation"] = display
        key = canonical_affiliation_key(display).casefold()
        grouped.setdefault(key, []).append(location)

    if len(grouped) == len(locations):
        return 0

    merged_locations: list[dict] = []
    for index, (_, bucket) in enumerate(
        sorted(grouped.items(), key=lambda item: str(item[1][0].get("affiliation") or "").casefold()),
        start=1,
    ):
        def _location_rank(item: dict) -> tuple[int, int, int]:
            level = str(item.get("geocode_level") or "")
            institute = 1 if level == "institute" else 0
            return (
                institute,
                int(item.get("speaker_count") or 0),
                int(item.get("talk_count") or 0),
            )

        primary = max(bucket, key=_location_rank)
        speakers: list[str] = []
        speaker_details: list[dict] = []
        talk_count = 0
        search_parts: list[str] = []
        for location in bucket:
            talk_count += int(location.get("talk_count") or 0)
            for speaker in location.get("speakers") or []:
                if speaker and speaker not in speakers:
                    speakers.append(speaker)
            speaker_details.extend(location.get("speaker_details") or [])
            if location.get("search_text"):
                search_parts.append(str(location["search_text"]))

        display = affiliation_display_name(primary.get("affiliation") or "") or primary.get(
            "affiliation"
        )
        merged = {
            **primary,
            "id": f"loc-{index:04d}",
            "affiliation": display,
            "speakers": speakers,
            "speaker_details": _merge_speaker_details(speaker_details),
            "speaker_count": len(speakers) or int(primary.get("speaker_count") or 0),
            "talk_count": talk_count or int(primary.get("talk_count") or 0),
            "search_text": " ".join([display, *search_parts]).lower(),
        }
        merged_locations.append(merged)

    payload["locations"] = merged_locations
    return 1


